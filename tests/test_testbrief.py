class ParseText(unittest.TestCase):
    """The block grammar on its own, without a transcript."""

    def test_a_finding_with_no_severity_is_a_parse_error_naming_the_finding_and_the_problem(self):
        shape = finding()
        del shape["severity"]
        report = testbrief.parse_text(block({"status": "ran", "reason": "", "findings": [shape]}))
        self.assertFalse(report.ok)
        self.assertEqual(report.error, "finding 1: severity is missing")

    def test_the_second_findings_problem_names_the_second_finding(self):
        report = testbrief.parse_text(block({"status": "ran", "reason": "",
                                             "findings": [finding(), finding(severity="critical")]}))
        self.assertFalse(report.ok)
        self.assertTrue(report.error.startswith("finding 2: "), report.error)

    def test_an_unknown_status_is_a_parse_error(self):
        report = testbrief.parse_text(block({"status": "done", "reason": "", "findings": []}))
        self.assertFalse(report.ok)
        self.assertIn("'done'", report.error)

    def test_a_not_run_report_needs_a_reason_and_carries_no_findings(self):
        self.assertIn("reason", testbrief.parse_text(
            block({"status": "not_run", "reason": "", "findings": []})).error)
        self.assertIn("no findings", testbrief.parse_text(
            block({"status": "not_run", "reason": "login page", "findings": [finding()]})).error)

    def test_a_ran_report_may_carry_no_reason_and_no_findings(self):
        report = testbrief.parse_text(block({"status": "ran", "findings": []}))
        self.assertTrue(report.ok, report.error)
        self.assertEqual((report.reason, report.findings), ("", ()))

    def test_a_block_that_is_not_an_object_or_whose_findings_are_not_an_array_is_an_error(self):
        self.assertIn("one JSON object", testbrief.parse_text(block([1, 2])).error)
        self.assertIn("findings must be an array", testbrief.parse_text(
            block({"status": "ran", "reason": "", "findings": {"a": 1}})).error)
        self.assertIn("reason must be a string", testbrief.parse_text(
            block({"status": "ran", "reason": 3, "findings": []})).error)

    def test_an_empty_or_missing_message_is_an_error(self):
        for text in ("", None, "no block here"):
            self.assertFalse(testbrief.parse_text(text).ok)

    def test_a_finding_keeps_its_card_and_extra_keys(self):
        report = testbrief.parse_text(block({"status": "ran", "reason": "", "findings": [
            finding(card="12", screenshot="shot.png")]}))
        self.assertTrue(report.ok, report.error)
        self.assertEqual(report.findings[0]["card"], "12")
        self.assertEqual(report.findings[0]["screenshot"], "shot.png")

    def test_an_envelope_block_is_not_a_report(self):
        text = "```relay-envelope\nstatus: complete\n```\n"
        self.assertFalse(testbrief.parse_text(text).ok)

    def test_a_triple_backtick_inside_an_observed_string_does_not_end_the_block(self):
        """Code review: the template sends copied page text to `observed`, and a page can show
        a code fence. The closing fence is a line of its own, so a fence inside a JSON string
        is body text."""
        shape = finding(observed="the page showed ```code``` in a box")
        text = "Toured.\n\n" + block({"status": "ran", "reason": "", "findings": [shape]})
        report = testbrief.parse_text(text)
        self.assertTrue(report.ok, report.error)
        self.assertEqual(report.findings[0]["observed"], "the page showed ```code``` in a box")

    def test_the_closing_fence_may_carry_a_carriage_return_and_trailing_spaces(self):
        text = ("```%s \r\n%s\r\n```  \r\n" % (contracts.TEST_REPORT_FENCE_TAG,
                                                json.dumps({"status": "ran", "findings": []})))
        self.assertTrue(testbrief.parse_text(text).ok)

    def test_the_fence_grammar_is_the_shared_one_from_contracts(self):
        self.assertEqual(testbrief._FENCE_RE.pattern,
                         contracts.fence_regex(contracts.TEST_REPORT_FENCE_TAG).pattern)


class FinalMessage(unittest.TestCase):
    """The reader `filing.py` shares: the last non sidechain assistant text, whole."""

    def write(self, lines):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        path = os.path.join(self.tmp.name, "t.jsonl")
        with open(path, "w") as handle:
            for line in lines:
                handle.write(json.dumps(line) + "\n")
        return path

    @staticmethod
    def assistant(text, sidechain=False):
        return {"type": "assistant", "isSidechain": sidechain,
                "message": {"role": "assistant", "content": [{"type": "text", "text": text}]}}

    def test_the_last_assistant_text_is_returned_whole(self):
        long = "x" * 5000
        path = self.write([self.assistant("first"), {"type": "user", "message": {"content": "hi"}},
                           self.assistant(long)])
        self.assertEqual(testbrief.final_message(path), long)

    def test_a_sidechain_message_after_the_final_one_is_skipped(self):
        path = self.write([self.assistant("final"), self.assistant("subagent", sidechain=True)])
        self.assertEqual(testbrief.final_message(path), "final")

    def test_text_blocks_of_one_message_are_joined_like_the_classifier_joins_them(self):
        path = self.write([{"type": "assistant", "message": {"content": [
            {"type": "text", "text": "a"}, {"type": "tool_use", "id": "t", "name": "Read",
                                            "input": {}}, {"type": "text", "text": "b"}]}}])
        self.assertEqual(testbrief.final_message(path), "a\nb")

    def test_no_assistant_text_at_all_is_none(self):
        path = self.write([{"type": "user", "message": {"content": "hi"}}])
        self.assertIsNone(testbrief.final_message(path))
        self.assertIsNone(testbrief.final_message(path + ".missing"))


