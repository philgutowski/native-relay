class ParseFromTheTranscript(unittest.TestCase):
    """The parser reads the full final message from the transcript, never the digest."""

    def test_a_final_message_ending_in_a_valid_block_parses_to_its_findings(self):
        report = testbrief.parse(fixture("test_report.jsonl"))
        self.assertTrue(report.ok, report.error)
        self.assertEqual(report.status, testloop.RAN)
        self.assertEqual([f["title"][:9] for f in report.findings], ["Finding 1", "Finding 2"])
        self.assertEqual([f["severity"] for f in report.findings], ["high", "medium"])
        self.assertEqual(report.findings[0]["cause"], {"file": "app/search.py", "line": 41,
                                                       "verdict": "defect"})

    def test_two_blocks_the_last_one_wins(self):
        report = testbrief.parse(fixture("test_report_two_blocks.jsonl"))
        self.assertTrue(report.ok, report.error)
        self.assertEqual([f["title"][:9] for f in report.findings], ["Finding 1"])

    def test_a_block_followed_by_more_prose_is_still_read(self):
        text = testbrief.final_message(fixture("test_report.jsonl"))
        self.assertFalse(text.rstrip().endswith("```"), "the fixture should end in prose")
        self.assertTrue(testbrief.parse(fixture("test_report.jsonl")).ok)

    def test_no_block_is_a_parse_error_naming_the_tag(self):
        report = testbrief.parse(fixture("test_report_none.jsonl"))
        self.assertFalse(report.ok)
        self.assertIn(contracts.TEST_REPORT_FENCE_TAG, report.error)
        self.assertEqual(report.findings, ())

    def test_malformed_json_is_a_parse_error_naming_json(self):
        report = testbrief.parse(fixture("test_report_malformed.jsonl"))
        self.assertFalse(report.ok)
        self.assertIn("not valid JSON", report.error)

    def test_a_not_run_report_with_a_reason_parses_with_no_findings(self):
        report = testbrief.parse(fixture("test_report_not_run.jsonl"))
        self.assertTrue(report.ok, report.error)
        self.assertEqual(report.status, testloop.NOT_RUN)
        self.assertIn("sign in", report.reason)
        self.assertEqual(report.findings, ())

    def test_a_report_longer_than_the_digest_tail_with_ten_findings_parses_whole(self):
        path = fixture("test_report_ten.jsonl")
        text = testbrief.final_message(path)
        self.assertGreater(len(text), classify.LAST_MESSAGE_CHARS)
        # The digest's tail cannot hold it: what classify keeps has no block in it.
        tail = text[-classify.LAST_MESSAGE_CHARS:]
        self.assertIsNone(testbrief.last_block(tail))
        report = testbrief.parse(path)
        self.assertTrue(report.ok, report.error)
        self.assertEqual(len(report.findings), 10)
        self.assertEqual([f["title"][:10] for f in report.findings][-1], "Finding 10")

    def test_the_digest_of_the_same_transcript_would_lose_the_report(self):
        """The reason the parser reads the transcript: `classify` keeps 200 characters at each
        end of the final message, and the report lives in the middle of a message that long."""
        class Result:
            timed_out = False
            exit_code = 0
        digest = classify.classify(fixture("test_report.jsonl"), Result())
        self.assertIsNone(testbrief.last_block(digest["last_message_tail"] or ""))
        self.assertIsNone(testbrief.last_block(digest["last_message"] or ""))
        self.assertTrue(testbrief.parse(fixture("test_report.jsonl")).ok)

    def test_a_missing_transcript_is_a_parse_error_not_an_exception(self):
        report = testbrief.parse(os.path.join(TRANSCRIPTS, "does-not-exist.jsonl"))
        self.assertFalse(report.ok)
        self.assertIn("no final message", report.error)


